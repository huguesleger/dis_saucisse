/// Visual variants of [DsButton].
enum DsButtonVariant {
  /// Mustard background: the main action of a screen ("Garder", "Trier mes photos").
  primary,

  /// Dark background with yellow text: the main call to action of the home screen ("Lancer le tri").
  dark,

  /// Cream background with a border ("Plus tard", "Garder sur le téléphone").
  secondary,

  /// White background ("Écarter", "Fermer").
  light,
}
